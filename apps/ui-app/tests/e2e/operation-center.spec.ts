import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { test, expect, openApp } from './fixtures';

test('operation context preserves project-filtered navigation, settings and evidence workflows', async ({ page }) => {
  await openApp(page, 'projects');
  await expect(page.locator('#projects-detail-title')).not.toBeEmpty();
  await expect(page.locator('.projects-tabs [role="tab"]')).toHaveCount(3);
  await page.locator('#project-tab-facts').focus(); await page.keyboard.press('ArrowRight');
  await expect(page.locator('#project-tab-graph')).toBeFocused();
  await expect(page.locator('#project-panel-graph')).toBeVisible();
  await page.locator('[data-action="projects.fullscreen"]').click();
  await expect.poll(() => page.evaluate(() => document.fullscreenElement?.id)).toBe('project-panel-graph');
  await page.locator('[data-action="projects.fullscreen"]').click();
  await page.locator('#project-tab-conversations').click();
  await expect(page.locator('#project-conversations-list')).not.toBeEmpty();
  await page.screenshot({ path: join(tmpdir(), 'opencode', 'operation-conversations-desktop.png') });
  await page.locator('[data-action="projects.settings"]').click();
  await expect(page.getByRole('dialog', { name: 'Project Settings', exact: true })).toBeVisible();
  await expect(page.locator('#project-scope-warning')).toContainText('no project scope limit');
  await page.locator('#project-edit-scope').fill('{invalid');
  page.once('dialog', dialog => dialog.accept());
  await page.locator('[data-action="projects.saveProjectSettings"]').click();
  await expect(page.locator('#project-edit-scope')).toHaveValue('{invalid');
  await page.locator('#project-edit-scope').fill('{"targets":["https://authorized.test"],"exclude":[]}');
  await page.locator('[data-action="projects.saveProjectSettings"]').click();
  await expect(page.locator('#project-settings-dialog')).not.toBeVisible();
  const assets = await page.locator('#project-assets-link').getAttribute('href');
  const projectId = new URLSearchParams(assets!.split('?')[1]).get('project_id')!;
  await page.locator('#project-assets-link').click();
  await expect(page.locator('#page-asset-management.active')).toBeVisible();
  await expect(page.locator('#asset-project-filter')).toHaveValue(projectId);
  await page.evaluate(() => { location.hash = 'operation-center'; });
  await expect(page.locator('#projects-detail-inner')).toBeVisible();
  await page.locator('#project-vulns-link').click();
  await expect(page.locator('#vulnerability-project-filter')).toHaveValue(projectId);
  await page.evaluate(() => { location.hash = 'operation-center'; });
  await page.locator('#project-tab-facts').click();
  await page.locator('#project-facts-search').fill('no-matching-evidence-482');
  await expect(page.locator('#project-facts-tbody')).toContainText('No matching');
  await page.locator('#project-facts-search').fill('');
  await page.screenshot({ path: join(tmpdir(), 'opencode', 'operation-facts-desktop.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('[data-action="projects.settings"]').click();
  await page.screenshot({ path: join(tmpdir(), 'opencode', 'operation-settings-mobile.png') });
  const fits = await page.locator('#project-settings-dialog').evaluate(dialog => dialog.scrollWidth <= dialog.clientWidth);
  expect(fits).toBe(true);
  await page.keyboard.press('Escape');
  await expect(page.locator('#project-settings-dialog')).not.toBeVisible();
});
