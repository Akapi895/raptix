import { test, expect } from '@playwright/test'
import { mkdir, writeFile, rm, symlink } from 'node:fs/promises'
import * as path from 'node:path'

test('new API planning missing/partial/valid/invalid/unavailable states, reload, scope and no fallback', async ({ page, request }) => {
  test.setTimeout(90000)
  const root = process.env.W04_TEST_WORKSPACE!
  const api = 'http://127.0.0.1:5281/api'
  expect((await (await request.get(`${api}/capabilities`)).json()).capabilities.planning).toEqual({ supported: true, available: true })
  const suffix = Date.now()
  const slug = `w04-browser-${suffix}`
  const target = 'http://authorized-planning-test.invalid'
  const create = await request.post(`${api}/engagements`, { data: { name: slug, targetType: 'web_url', targetValue: target, authorizationConfirmed: true } })
  expect(create.status()).toBe(201)
  const project = await create.json()
  const plan = path.join(root, slug, 'plan')
  const heading = page.getByRole('heading', { name: 'Planning handoff blocked', exact: true })
  await page.goto(`/projects/${project.id}/charter`)
  await expect(heading).toBeVisible()
  await expect(page.getByText('roe: missing', { exact: true })).toBeVisible()
  const roe = { engagement_name: 'W04 Verified', client: 'Controlled client', start_date: '2026-10-02', end_date: '2026-10-31', engagement_type: 'external', testing_window: 'Mon-Fri 09:00-17:00 UTC', authorization_reference: 'W04 local test approval', in_scope: [{ target, type: 'web-url', notes: 'Controlled target' }], out_of_scope: [{ target: 'http://excluded.invalid', type: 'web-url', notes: 'Excluded system' }], prohibited_actions: ['No production changes'], permitted_actions: ['Read-only assessment'] }
  await writeFile(path.join(plan, 'roe.json'), JSON.stringify(roe))
  await page.getByRole('button', { name: 'Refresh planning' }).click()
  await expect(page.getByText('Controlled client', { exact: false })).toBeVisible()
  await expect(heading).toBeVisible()
  await page.getByRole('button', { name: 'Scope & Boundary', exact: true }).click()
  await expect(page.getByRole('cell', { name: target, exact: true })).toBeVisible()
  await expect(page.getByRole('cell', { name: 'http://excluded.invalid', exact: true })).toBeVisible()
  await expect(page.getByText('No production changes', { exact: true })).toBeVisible()
  const rest = { conops: { engagement_name: 'W04 Verified', executive_summary: 'W04 source-backed operational concept' }, deconfliction: { engagement_name: 'W04 Verified', deconfliction_code: 'PRIVATE-CODE', identifiers: [{ type: 'source-ip', value: '192.0.2.55' }] }, 'threat-profile': { engagement_name: 'W04 Verified', actor_name: 'Test', tier: 'tier-1', sophistication: 'low', motivation: 'testing' }, contact: { engagement_name: 'W04 Verified', primary_operator: { name: 'Operator', role: 'Owner', channel: 'local' } }, 'data-handling': { engagement_name: 'W04 Verified' }, abort: { engagement_name: 'W04 Verified' }, cleanup: { engagement_name: 'W04 Verified' } }
  for (const [name, doc] of Object.entries(rest)) await writeFile(path.join(plan, `${name}.json`), JSON.stringify(doc))
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Planning bundle validated', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Charter & ROE', exact: true }).click()
  await expect(page.getByText('W04 source-backed operational concept', { exact: true })).toBeVisible()
  await expect(page.getByText('opplan: missing', { exact: true })).toBeVisible()
  const docs = await request.get(`${api}/engagements/${project.id}/plan-docs`)
  expect((await docs.text())).not.toContain('PRIVATE-CODE')
  expect((await request.post(`${api}/engagements/${project.id}/plan-docs`, { data: { roe: { in_scope: [] } } })).status()).toBe(404)
  await writeFile(path.join(plan, 'opplan.json'), JSON.stringify({ engagement_name: 'W04 Verified', threat_profile: 'Controlled test', objectives: [{ id: 'OBJ-W04', title: 'Verify read-only projection', description: 'Do not submit a runtime run', phase: 'recon', acceptance_criteria: ['Visible'], priority: 1, blocked_by: ['OBJ-PRIOR'], status: 'blocked' }] }))
  await page.getByRole('button', { name: 'Refresh planning' }).click()
  await expect(page.getByText('OBJ-W04 — Verify read-only projection', { exact: true })).toBeVisible()
  expect((await request.get(`${api}/engagements/${project.id}/opplan`)).status()).toBe(200)
  await writeFile(path.join(plan, 'roe.json'), '{broken')
  await page.reload()
  await expect(page.getByText('roe: invalid', { exact: true })).toBeVisible()
  await expect(page.getByRole('cell', { name: target, exact: true })).toHaveCount(0)
  await writeFile(path.join(plan, 'roe.json'), JSON.stringify(roe))
  await rm(path.join(plan, 'cleanup.json')); await mkdir(path.join(plan, 'cleanup.json'))
  await page.getByRole('button', { name: 'Refresh planning' }).click()
  await expect(page.getByText('cleanup: unavailable', { exact: true })).toBeVisible()
  await rm(path.join(plan, 'cleanup.json'), { recursive: true }); await writeFile(path.join(plan, 'cleanup.json'), JSON.stringify(rest.cleanup))
  const otherResponse = await request.post(`${api}/engagements`, { data: { name: `${slug}-other`, targetType: 'ip_range', targetValue: '192.0.2.0/24', authorizationConfirmed: true } })
  expect(otherResponse.status()).toBe(201)
  const other = await otherResponse.json()
  await page.goto(`/projects/${other.id}/charter`)
  await expect(page.getByText('roe: missing', { exact: true })).toBeVisible()
  await expect(page.getByText('W04 source-backed operational concept', { exact: true })).toHaveCount(0)
  const otherPlan = path.join(root, other.workspaceSlug, 'plan')
  await rm(otherPlan, { recursive: true }); await symlink(plan, otherPlan, 'junction')
  const rejected = await request.get(`${api}/engagements/${other.id}/plan-docs`)
  expect((await rejected.json()).bundle.roe).toBe('unavailable')
  await page.route(`**/api/engagements/${project.id}/plan-docs`, route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ statusCode: 503, error: { code: 'unavailable', message: 'W04 controlled planning outage' } }) }))
  await page.goto(`/projects/${project.id}/charter`)
  await expect(page.getByText('W04 controlled planning outage', { exact: true })).toBeVisible()
  await expect(page.getByText('W04 source-backed operational concept', { exact: true })).toHaveCount(0)
  await expect(page.getByText('Alex Kim', { exact: true })).toHaveCount(0)
  await expect(page.locator('aside nav').getByRole('button')).toHaveCount(13)
  await page.unroute(`**/api/engagements/${project.id}/plan-docs`)
  const validView = await (await request.get(`${api}/engagements/${project.id}/plan-docs`)).json()
  await page.route(`**/api/engagements/${project.id}/plan-docs`, route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ ...validView, engagementId: other.id }) }))
  await page.getByRole('button', { name: 'Refresh planning' }).click()
  await expect(page.getByText('Planning response did not match this engagement', { exact: true })).toBeVisible()
  await expect(page.getByText('W04 source-backed operational concept', { exact: true })).toHaveCount(0)
  await page.unroute(`**/api/engagements/${project.id}/plan-docs`)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Planning bundle validated', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: test.info().outputPath('w04-real-planning-mobile.png'), fullPage: true })
})
