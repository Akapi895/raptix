import { test, expect } from '@playwright/test'

test('live new-API create, reload, conflict and project switching use server data only', async ({ page, request }) => {
  test.setTimeout(60000)
  const health = await request.get('http://127.0.0.1:5280/api/capabilities')
  expect(health.ok(), 'HEAD live gate requires the dedicated PostgreSQL-backed new API').toBe(true)
  const sourceRequests: string[] = []
  page.on('request', request => { if (request.url().includes('/api/')) sourceRequests.push(request.url()) })
  const suffix = Date.now().toString()
  const slug = `w03-browser-${suffix}`
  await page.goto('/projects')
  await expect(page.getByRole('heading', { name: 'Projects Management' })).toBeVisible()
  await page.getByRole('button', { name: 'New Project', exact: true }).click()
  await page.getByLabel('Display Name', { exact: false }).fill(`W03 Browser ${suffix}`)
  await page.getByLabel('Workspace Slug', { exact: false }).fill(slug)
  await page.locator('#real-new-project-target').fill('http://authorized-ui-test.invalid')
  await page.locator('#real-new-project-brief').fill('Authorized UI-driven create test brief with scoped constraints.')
  await page.getByRole('checkbox').check()
  const createdResponse = page.waitForResponse(response => response.url().endsWith('/api/engagements') && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Create Project', exact: true }).click()
  const response = await createdResponse
  expect(response.status()).toBe(201)
  const created = await response.json()
  expect(created.brief).toContain('Authorized UI-driven create test brief')
  expect(created.handoffConfirmedAt).toBeNull()
  // Briefing-first flow: creation lands in the Operator Console, not Charter.
  await expect(page).toHaveURL(`/projects/${created.id}/console`)
  await expect(page.getByText('Plan status')).toBeVisible()
  await page.goto(`/projects/${created.id}/charter`)
  await expect(page.getByRole('heading', { name: `W03 Browser ${suffix} — Charter & Rules of Engagement` })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Planning handoff blocked', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: `W03 Browser ${suffix} — Charter & Rules of Engagement` })).toBeVisible()
  await expect(page.locator('aside nav').getByRole('button')).toHaveCount(13)
  await expect(page.getByText('Alex Kim', { exact: true })).toHaveCount(0)
  await page.goto('/projects')
  await page.getByRole('button', { name: 'New Project', exact: true }).click()
  await page.getByLabel('Workspace Slug', { exact: false }).fill(slug)
  await page.locator('#real-new-project-target').fill('http://authorized-ui-test.invalid')
  await page.locator('#real-new-project-brief').fill('Authorized UI-driven create test brief with scoped constraints.')
  await page.getByRole('checkbox').check()
  await page.getByRole('button', { name: 'Create Project', exact: true }).click()
  await expect(page.getByText(/already exists/).first()).toBeVisible()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  const second = await request.post('http://127.0.0.1:5280/api/engagements', { data: { name: `${slug}-second`, targetType: 'ip_range', targetValue: '192.0.2.0/24', authorizationConfirmed: true, brief: 'Authorized second create test brief with scoped constraints.' } })
  expect(second.status()).toBe(201)
  const other = await second.json()
  await page.goto(`/projects/${other.id}/charter`)
  await expect(page.locator('#main-content')).toContainText(other.workspaceSlug)
  await page.goto(`/projects/${created.id}/charter`)
  await expect(page.locator('#main-content')).toContainText(slug)
  await expect(page.locator('#main-content')).not.toContainText(other.workspaceSlug)
  expect(sourceRequests.some(url => url.includes('3000'))).toBe(false)
  await page.screenshot({ path: test.info().outputPath('w03-real-project.png'), fullPage: true })
})

test('real-mode backend unavailable response stays an error without demo fallback', async ({ page }) => {
  await page.route('**/api/engagements', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ statusCode: 503, error: { code: 'unavailable', message: 'Controlled backend unavailable' } }) }))
  await page.goto('/projects')
  await expect(page.getByText('Controlled backend unavailable', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: /Retry|Refresh/ }).first()).toBeVisible()
  await expect(page.getByText('Acme Corp External Assessment', { exact: true })).toHaveCount(0)
  await expect(page.getByText('Alex Kim', { exact: true })).toHaveCount(0)
})
