import { beforeEach, afterEach, describe, expect, it, vi } from 'vitest'

let storage: Map<string, string>
beforeEach(() => {
  storage = new Map()
  vi.stubGlobal('window', { localStorage: { getItem: (key: string) => storage.get(key) ?? null, setItem: (key: string, value: string) => storage.set(key, value) } })
  vi.useFakeTimers()
  vi.resetModules()
})
afterEach(() => { vi.clearAllTimers(); vi.useRealTimers(); vi.unstubAllGlobals() })

describe('shared mock run lifecycle', () => {
  it('has a stable initial snapshot without notifying listeners during render reads', async () => {
    const store = await import('../../src/features/agent-runs/store')
    const listener = vi.fn()
    store.subscribeRuns(listener)
    const snapshot = store.getRunSnapshot('1')
    expect(snapshot.projectId).toBe('1')
    expect(store.getRunSnapshot('1')).toBe(snapshot)
    expect(listener).not.toHaveBeenCalled()
  })
  it('isolates projects and suppresses duplicate submissions while a reply is pending', async () => {
    const store = await import('../../src/features/agent-runs/store')
    const second = store.getRunSnapshot('2')
    const thread = store.createThread('1')
    expect(store.submitMessage('1', thread, 'Inspect sample output')).toBe(true)
    expect(store.submitMessage('1', thread, 'Inspect sample output')).toBe(false)
    await vi.advanceTimersByTimeAsync(1000)
    expect(store.getRunSnapshot('1').threads.find(candidate => candidate.id === thread)?.messages.filter(message => message.role === 'user')).toHaveLength(1)
    expect(store.getRunSnapshot('2')).toBe(second)
  })
  it('stops pending replies and never decides an approval on a snapshot read', async () => {
    const store = await import('../../src/features/agent-runs/store')
    const thread = store.createThread('1')
    store.submitMessage('1', thread, 'Wait for sample reply')
    const count = store.getRunSnapshot('1').threads[0].messages.length
    store.setRunState('1', 'stopped')
    await vi.advanceTimersByTimeAsync(1000)
    expect(store.getRunSnapshot('1').threads[0].messages).toHaveLength(count)
    expect(store.getRunSnapshot('1').approvals).toEqual({})
    expect(store.decideApproval('1', { agentId: 'exploit-1', decision: 'rejected' })).toBe(true)
    expect(store.decideApproval('1', { agentId: 'exploit-1', decision: 'approved' })).toBe(false)
    expect(store.getRunSnapshot('2').approvals).toEqual({})
  })
  it('recovers a created thread after reload without resubmitting its pending message', async () => {
    const store = await import('../../src/features/agent-runs/store')
    const thread = store.createThread('1')
    store.submitMessage('1', thread, 'Do not resubmit after reload')
    vi.clearAllTimers()
    vi.resetModules()
    const reloaded = await import('../../src/features/agent-runs/store')
    const snapshot = reloaded.getRunSnapshot('1')
    expect(snapshot.activeThreadId).toBe(thread)
    expect(snapshot.threads.find(candidate => candidate.id === thread)?.messages.filter(message => message.role === 'user')).toHaveLength(1)
    expect(snapshot.pendingThreadIds).toEqual([])
  })
  it('recovers messages sent to a seeded thread and reapplies acknowledged approval state', async () => {
    const store = await import('../../src/features/agent-runs/store')
    expect(store.submitMessage('1', 'chat-1', 'Preserve seeded-thread operator history')).toBe(true)
    await vi.advanceTimersByTimeAsync(1000)
    expect(store.decideApproval('1', { agentId: 'exploit-1', decision: 'approved' })).toBe(true)
    vi.resetModules()
    const reloaded = await import('../../src/features/agent-runs/store')
    const snapshot = reloaded.getRunSnapshot('1')
    expect(snapshot.threads.find(thread => thread.id === 'chat-1')?.messages.some(message => message.content === 'Preserve seeded-thread operator history')).toBe(true)
    expect(snapshot.agents.find(agent => agent.id === 'exploit-1')?.status).toBe('running')
  })
  it('separates simulated connection loss from execution failure and exposes deterministic HITL/completion states', async () => {
    const store = await import('../../src/features/agent-runs/store')
    store.configureMockScenario('1', 'active')
    store.configureMockScenario('1', 'disconnected')
    expect(store.getRunSnapshot('1').runState).toBe('running')
    expect(store.getRunSnapshot('1').executionError).toBeUndefined()
    store.configureMockScenario('1', 'reconnecting')
    expect(store.getRunSnapshot('1').connectionState).toBe('reconnecting')
    store.configureMockScenario('1', 'failed')
    expect(store.getRunSnapshot('1').executionError).toContain('Simulated runtime failure')
    expect(store.getRunSnapshot('1').runState).toBe('stopped')
    store.configureMockScenario('1', 'completed')
    expect(store.getRunSnapshot('1').agents.every(agent => agent.status === 'done')).toBe(true)
    store.configureMockScenario('1', 'hitl')
    expect(store.getRunSnapshot('1').agents.some(agent => agent.status === 'blocked')).toBe(true)
    expect(store.getRunSnapshot('2').scenario).toBe('default')
  })
  it('rejects a stale duplicate approval from another already-open mock session', async () => {
    const first = await import('../../src/features/agent-runs/store')
    first.getRunSnapshot('1')
    vi.resetModules()
    const second = await import('../../src/features/agent-runs/store')
    second.getRunSnapshot('1')
    expect(first.decideApproval('1', { agentId: 'exploit-1', decision: 'rejected' })).toBe(true)
    expect(second.decideApproval('1', { agentId: 'exploit-1', decision: 'approved' })).toBe(false)
    expect(second.getRunSnapshot('1').approvals['exploit-1']).toBe('rejected')
  })
  it('starts an idle root agent and preserves its running status after reload', async () => {
    const store = await import('../../src/features/agent-runs/store')
    expect(store.getRunSnapshot('new-project').runState).toBe('stopped')
    store.setRunState('new-project', 'running')
    expect(store.getRunSnapshot('new-project').agents.find(agent => agent.id === 'root')?.status).toBe('running')
    vi.resetModules()
    const reloaded = await import('../../src/features/agent-runs/store')
    expect(reloaded.getRunSnapshot('new-project').agents.find(agent => agent.id === 'root')?.status).toBe('running')
  })
  it('stops running agent instances without resurrecting them on reload', async () => {
    const store = await import('../../src/features/agent-runs/store')
    store.getRunSnapshot('1')
    store.setRunState('1', 'stopped')
    expect(store.getRunSnapshot('1').agents.some(agent => agent.status === 'running')).toBe(false)
    vi.resetModules()
    const reloaded = await import('../../src/features/agent-runs/store')
    expect(reloaded.getRunSnapshot('1').runState).toBe('stopped')
    expect(reloaded.getRunSnapshot('1').agents.some(agent => agent.status === 'running')).toBe(false)
    reloaded.setRunState('1', 'running')
    expect(reloaded.getRunSnapshot('1').agents.find(agent => agent.id === 'root')?.status).toBe('running')
  })
})
