import * as path from 'node:path';
import { readFile, readdir, stat } from 'node:fs/promises';
import type { PrismaClient } from '../generated/prisma/client.js';
import { resolveEngagementWorkspaceDir } from '../security/workspace-policy.js';
import { ProjectNotFoundError } from './projects-service.js';

/**
 * W14 engagement export: JSON and Markdown attachment endpoints with strict
 * server-side format validation — unsupported formats answer 400, they never
 * silently fall back to Markdown like the legacy route. Payload is the actual
 * engagement DTO, actual plan documents and the raw `FIND-*.md` contents of
 * the owned workspace; unreadable findings are skipped and counted, never
 * fabricated.
 */

export const EXPORT_FORMATS = ['json', 'markdown'] as const;
export type ExportFormat = (typeof EXPORT_FORMATS)[number];

export function isExportFormat(value: unknown): value is ExportFormat {
  return typeof value === 'string' && (EXPORT_FORMATS as readonly string[]).includes(value);
}

interface ExportPayload {
  engagement: Record<string, unknown>;
  planDocs: Record<string, unknown>;
  findings: Array<{ id: string; content: string }>;
  findingsUnreadable: number;
}

export interface ExportResult {
  readonly filename: string;
  readonly contentType: string;
  readonly body: string;
}

const MAX_FINDINGS = 100;
const MAX_FILE_BYTES = 256 * 1024;
const PLAN_DOC_NAMES = ['roe.json', 'conops.json', 'deconfliction.json', 'opplan.json'] as const;

export class ExportService {
  public constructor(private readonly db: PrismaClient, private readonly workspaceRoot: string) {}

  public async export(userId: string, engagementId: string, format: ExportFormat): Promise<ExportResult> {
    const project = await this.db.engagement.findFirst({ where: { id: engagementId, userId } });
    if (!project) throw new ProjectNotFoundError();
    const payload = await this.collect(project.name, engagementId);
    if (format === 'json') {
      return {
        filename: `${project.name}-export.json`,
        contentType: 'application/json',
        body: `${JSON.stringify({ ...payload, formatValidated: true }, null, 2)}\n`,
      };
    }
    return {
      filename: `${project.name}-export.md`,
      contentType: 'text/markdown; charset=utf-8',
      body: buildMarkdown(project.name, payload),
    };
  }

  private async collect(slug: string, engagementId: string): Promise<ExportPayload> {
    const dir = await resolveEngagementWorkspaceDir(this.workspaceRoot, slug);
    const planDocs: Record<string, unknown> = {};
    for (const docName of PLAN_DOC_NAMES) {
      try {
        const content = await readFile(path.join(dir, 'plan', docName), 'utf8');
        planDocs[docName.replace('.json', '')] = JSON.parse(content) as unknown;
      } catch { /* absent plan document stays absent */ }
    }
    const findings: ExportPayload['findings'] = [];
    let findingsUnreadable = 0;
    let names: string[] = [];
    try {
      names = (await readdir(path.join(dir, 'findings'))).filter(name => name.startsWith('FIND-') && name.endsWith('.md')).sort();
    } catch { /* no findings directory yet */ }
    for (const name of names.slice(0, MAX_FINDINGS)) {
      try {
        const file = path.join(dir, 'findings', name);
        const info = await stat(file);
        if (!info.isFile() || info.size > MAX_FILE_BYTES) { findingsUnreadable += 1; continue; }
        findings.push({ id: name.replace(/\.md$/, ''), content: await readFile(file, 'utf8') });
      } catch {
        findingsUnreadable += 1;
      }
    }
    return {
      engagement: { id: engagementId, name: slug },
      planDocs,
      findings,
      findingsUnreadable,
    };
  }
}

function buildMarkdown(slug: string, payload: ExportPayload): string {
  const lines: string[] = [
    `# ${slug} — Engagement Export`,
    '',
    `Generated by the new API export endpoint; JSON/Markdown are the only supported formats.`,
    '',
  ];
  const entries = Object.entries(payload.planDocs);
  if (entries.length > 0) {
    lines.push('## Plan documents', '');
    for (const [name, doc] of entries) {
      lines.push(`### ${name}`, '', '```json', JSON.stringify(doc, null, 2), '```', '');
    }
  }
  if (payload.findings.length > 0 || payload.findingsUnreadable > 0) {
    lines.push('## Findings', '');
    for (const finding of payload.findings) {
      lines.push(`### ${finding.id}`, '', finding.content, '');
    }
    if (payload.findingsUnreadable > 0) {
      lines.push(`> ${payload.findingsUnreadable} finding file(s) unreadable or oversized and omitted from this export.`, '');
    }
  }
  return lines.join('\n');
}
