function fail(message: string): never {
  console.error(`capture-legacy: REFUSED: ${message}`)
  process.exit(2)
}

function realResolve(target: string): string {
  let current = path.resolve(target)
  const tail: string[] = []
  for (;;) {
    try {
      return path.join(realpathSync(current), ...tail.reverse())
    } catch {
      const parent = path.dirname(current)
      if (parent === current) return current
      tail.push(path.basename(current))
      current = parent
    }
  }
}

function isWithin(child: string, root: string, allowEqual: boolean): boolean {
  const c = child.toLowerCase()
  const r = root.toLowerCase()
  if (c === r) return allowEqual
  if (!c.startsWith(r)) return false
  return c[r.length] === '\\' || c[r.length] === '/'
}

function parseArgs(argv: string[]): Map<string, string> {
  const args = new Map<string, string>()
  if (argv.length % 2 !== 0) fail(`arguments must be "--flag value" pairs, got odd count: ${argv.join(' ')}`)
  for (let i = 0; i < argv.length; i += 2) {
    const flag = argv[i]
    if (!flag.startsWith('--')) fail(`expected a --flag, got "${flag}"`)
    const name = flag.slice(2)
    if (!ALLOWED_FLAGS.has(name)) fail(`unknown flag --${name}; allowed: ${[...ALLOWED_FLAGS].join(', ')}`)
    args.set(name, argv[i + 1])
  }
  return args
}

function requiredArg(args: Map<string, string>, name: string): string {
  const value = args.get(name)
  if (value === undefined || value === '') fail(`missing required --${name}`)
  return value
}

function assertBaseUrl(raw: string): string {
  let parsed: URL
  try {
    parsed = new URL(raw)
  } catch {
    fail(`--base-url is not a valid URL: "${raw}"`)
  }
  if (
    parsed.protocol !== 'http:' ||
    parsed.hostname !== '127.0.0.1' ||
    parsed.port !== '5290' ||
    (parsed.pathname !== '/' && parsed.pathname !== '') ||
    parsed.search !== '' ||
    parsed.hash !== '' ||
    parsed.username !== '' ||
    parsed.password !== ''
  ) {
    fail(`--base-url must be exactly ${ALLOWED_BASE_URL}, got "${raw}"; refusing any other origin`)
  }
  return ALLOWED_BASE_URL
}

function assertWorkspace(raw: string): string {
  const resolved = realResolve(raw)
  if (!isWithin(resolved, ALLOWED_WORKSPACE_ROOT, true)) {
    fail(`--workspace must resolve under ${ALLOWED_WORKSPACE_ROOT}, got "${resolved}"`)
  }
  try {
    statSync(path.join(resolved, CAPTURE_MARKER))
  } catch {
    fail(`--workspace must be the HEAD-provisioned isolated capture root containing ${CAPTURE_MARKER}; got "${resolved}"`)
  }
  mkdirSync(resolved, { recursive: true })
  return resolved
}

