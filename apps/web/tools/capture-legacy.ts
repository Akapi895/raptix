function makeRequest(baseUrl: string) {
  return async function request(method: string, urlPath: string, body?: unknown): Promise<Capture> {
    const res = await fetch(`${baseUrl}${urlPath}`, {
      method,
      headers: body === undefined ? undefined : { 'content-type': 'application/json' },
      body: body === undefined ? undefined : JSON.stringify(body),
      signal: AbortSignal.timeout(REQUEST_TIMEOUT_MS),
    })
    const contentType = res.headers.get('content-type')
    const contentDisposition = res.headers.get('content-disposition')
    let text = await res.text()
    if (text.length > MAX_BODY_CHARS) text = text.slice(0, MAX_BODY_CHARS)
    let parsed: unknown = text
    if (contentType?.includes('application/json')) {
      try {
        parsed = JSON.parse(text)
      } catch {
        parsed = text
      }
    }
    const capture: Capture = {
      provenance: 'legacy-http-controlled',
      method,
      path: urlPath,
      status: res.status,
      contentType,
      body: parsed,
    }
    if (contentDisposition !== null) capture.contentDisposition = contentDisposition
    return capture
  }
}

