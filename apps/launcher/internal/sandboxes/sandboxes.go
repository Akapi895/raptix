// Package sandboxes provisions one sandbox container per web project (ADR-0086 A).
//
// Each project's sandbox mounts only that project's directory of the shared
// workspace volume, at the same path the runtime and API use (/workspace/<slug>),
// and runs as its own engagement root. Names and paths here must match what the
// web server routes to (apps/web/server/src/services/runtime/sandbox-routing.ts):
// the container and DNS host are "sbx-<slug>" and the port is 9999.
package sandboxes

import (
	"bytes"
	"fmt"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"text/template"
)

// HostPrefix names a project's sandbox container and its DNS host.
const HostPrefix = "sbx-"

// Port is the sandbox daemon port (the server routes to it).
const Port = 9999

// maxSlugLen keeps "sbx-<slug>" within the 63-character DNS label limit.
const maxSlugLen = 63 - len(HostPrefix)

var slugRE = regexp.MustCompile(`^[a-z0-9](?:[a-z0-9-]{0,57}[a-z0-9])?$`)

// ValidSlug reports whether slug can name a sandbox host.
func ValidSlug(slug string) error {
	if len(slug) > maxSlugLen {
		return fmt.Errorf("slug %q is longer than %d characters", slug, maxSlugLen)
	}
	if !slugRE.MatchString(slug) {
		return fmt.Errorf("slug %q must be lowercase letters, digits and dashes, starting and ending with a letter or digit", slug)
	}
	return nil
}

// ContainerName returns the sandbox container (and DNS host) for a project.
func ContainerName(slug string) (string, error) {
	if err := ValidSlug(slug); err != nil {
		return "", err
	}
	return HostPrefix + slug, nil
}

// ComposeProject returns the compose project name owning a project's sandbox.
func ComposeProject(slug string) string {
	return "raptix-" + HostPrefix + slug
}

// Settings are the deployment values a sandbox compose file needs.
type Settings struct {
	// Image is the sandbox image reference, e.g. ghcr.io/akapi895/raptix-sandbox:stable.
	Image string
	// Network is the existing sandbox network the runtime is attached to.
	Network string
	// Volume is the existing workspace volume holding every project directory.
	Volume string
	// EnvFile is the deployment .env, used for the shared sandbox configuration.
	EnvFile string
}

// capAdd mirrors the web-sandbox service in docker-compose.web-runtime.yml.
var capAdd = []string{"NET_RAW", "NET_ADMIN", "NET_BIND_SERVICE", "SYS_PTRACE", "SETUID", "SETGID", "CHOWN", "DAC_OVERRIDE", "FOWNER", "KILL"}

var composeTemplate = template.Must(template.New("sandbox").Parse(`# Generated by "raptix web sandboxes sync" for project {{.Slug}} (ADR-0086 A). Do not edit.
# The service is named after the container, not "sandbox": compose gives a service its name as
# a network alias, and every project sandbox shares sandbox-net, so "sandbox" would resolve
# round-robin across all projects' sandboxes.
services:
  {{.Container}}:
    image: {{.Image}}
    container_name: {{.Container}}
    env_file: {{.EnvFile}}
    environment:
      SANDBOX_DAEMON: '1'
      RAPTIX_ENGAGEMENT: '{{.Slug}}'
      RAPTIX_ENGAGEMENT_WORKSPACE: ''
      NEO4J_URI: bolt://neo4j:7687
      NEO4J_USER: neo4j
      NEO4J_PASSWORD: ${NEO4J_PASSWORD:-raptix-graph}
    volumes:
      - type: volume
        source: workspace
        target: /workspace/{{.Slug}}
        volume:
          subpath: {{.Slug}}
    networks: [sandbox-net]
    cap_drop: [ALL]
    cap_add: [{{.CapAdd}}]
    security_opt: [no-new-privileges:true]
    mem_limit: 4g
    pids_limit: 4096
    init: true
    restart: unless-stopped
volumes:
  workspace:
    external: true
    name: {{.Volume}}
networks:
  sandbox-net:
    external: true
    name: {{.Network}}
`))

// RenderCompose returns the compose file that runs one project's sandbox.
func RenderCompose(slug string, s Settings) ([]byte, error) {
	container, err := ContainerName(slug)
	if err != nil {
		return nil, err
	}
	if s.Image == "" || s.Network == "" || s.Volume == "" || s.EnvFile == "" {
		return nil, fmt.Errorf("sandbox settings need image, network, volume and env file")
	}
	var buf bytes.Buffer
	data := map[string]string{
		"Slug":      slug,
		"Container": container,
		"Image":     s.Image,
		"Network":   s.Network,
		"Volume":    s.Volume,
		"EnvFile":   "'" + strings.ReplaceAll(filepath.ToSlash(s.EnvFile), "'", "''") + "'",
		"CapAdd":    strings.Join(capAdd, ", "),
	}
	if err := composeTemplate.Execute(&buf, data); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// Plan decides which projects need a sandbox started and which sandbox containers are
// orphaned (their project directory is gone). It is pure so the rule is testable without Docker.
func Plan(projects []string, containers []string) (ensure []string, orphaned []string) {
	have := map[string]bool{}
	for _, p := range projects {
		if ValidSlug(p) == nil {
			have[p] = true
		}
	}
	running := map[string]bool{}
	for _, c := range containers {
		if strings.HasPrefix(c, HostPrefix) {
			running[strings.TrimPrefix(c, HostPrefix)] = true
		}
	}
	for p := range have {
		ensure = append(ensure, p)
	}
	for c := range running {
		if !have[c] {
			orphaned = append(orphaned, HostPrefix+c)
		}
	}
	sort.Strings(ensure)
	sort.Strings(orphaned)
	return ensure, orphaned
}
