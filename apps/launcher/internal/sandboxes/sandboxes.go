// Package sandboxes provisions one sandbox container per web project (ADR-0086 A, ADR-0102).
//
// Each project's sandbox mounts its own named volume, raptix-ws-<slug>, at /workspace. The volume is not shared
// with any other project, and no path names a project. Names and paths here must match what the web server routes to
// (apps/api's sandbox-routing equivalent, once rebuilt per ADR-0106 — apps/web/server was removed): the container
// and DNS host are "sbx-<slug>" and the port is 9999.
package sandboxes

import (
	"bytes"
	"fmt"
	"regexp"
	"strings"
	"text/template"
)

// HostPrefix names a project's sandbox container and its DNS host.
const HostPrefix = "sbx-"

// VolumePrefix names a project's workspace volume.
const VolumePrefix = "raptix-ws-"

// Port is the sandbox daemon port (the server routes to it).
const Port = 9999

// maxSlugLen keeps "sbx-<slug>" within the 63-character DNS label limit.
const maxSlugLen = 63 - len(HostPrefix)

var slugRE = regexp.MustCompile(`^[a-z0-9](?:[a-z0-9-]{0,57}[a-z0-9])?$`)

// ValidSlug reports whether slug can name a sandbox host.
func ValidSlug(slug string) error {
	if len(slug) > maxSlugLen {
		return fmt.Errorf("slug %q is longer than %d characters", slug, maxSlugLen)
	}
	if !slugRE.MatchString(slug) {
		return fmt.Errorf("slug %q must be lowercase letters, digits and dashes, starting and ending with a letter or digit", slug)
	}
	return nil
}

// ContainerName returns the sandbox container (and DNS host) for a project.
func ContainerName(slug string) (string, error) {
	if err := ValidSlug(slug); err != nil {
		return "", err
	}
	return HostPrefix + slug, nil
}

// VolumeName returns the workspace volume of a project. The volume belongs to that project alone.
func VolumeName(slug string) (string, error) {
	if err := ValidSlug(slug); err != nil {
		return "", err
	}
	return VolumePrefix + slug, nil
}

// ComposeProject is the compose project every project sandbox joins. Each project keeps its own
// compose file and service, so its container starts, restarts and is removed without touching the others.
const ComposeProject = "raptix-sandbox"

// Settings are the deployment values a sandbox compose file needs.
type Settings struct {
	// Image is the sandbox image reference, e.g. ghcr.io/akapi895/raptix-sandbox:stable.
	Image string
	// Network is the existing sandbox network the runtime is attached to.
	Network string
}

// capAdd mirrors the sandbox hardening in docker-compose.web-runtime.yml.
var capAdd = []string{"NET_RAW", "NET_ADMIN", "NET_BIND_SERVICE", "SYS_PTRACE", "SETUID", "SETGID", "CHOWN", "DAC_OVERRIDE", "FOWNER", "KILL"}

// The sandbox receives no env file. Its environment is the allowlist below and nothing else, so provider keys, the
// admin password and the vault key of the deployment never reach a sandbox. The Neo4j host is not reachable from a
// sandbox on the web stack, so no Neo4j variable is passed.
var composeTemplate = template.Must(template.New("sandbox").Parse(`# Generated by the sandbox controller for project {{.Slug}} (ADR-0102). Do not edit.
# The project's own volume is mounted at /workspace. No other project's files are mounted, and no path names the project.
# The service is named after the container, not "sandbox": compose gives a service its name as a network alias,
# and every project sandbox shares sandbox-net, so "sandbox" would resolve round-robin across all projects' sandboxes.
services:
  {{.Container}}:
    image: {{.Image}}
    container_name: {{.Container}}
    environment:
      SANDBOX_DAEMON: '1'
      # Only this project's token: the daemon accepts no request from a peer sandbox, the runtime, or any other caller.
      SANDBOX_TOKEN: '{{.Token}}'
    volumes:
      - type: volume
        source: workspace
        target: /workspace
    networks: [sandbox-net]
    cap_drop: [ALL]
    cap_add: [{{.CapAdd}}]
    security_opt: [no-new-privileges:true]
    mem_limit: 4g
    pids_limit: 4096
    init: true
    restart: unless-stopped
volumes:
  workspace:
    name: {{.Volume}}
networks:
  sandbox-net:
    external: true
    name: {{.Network}}
`))

// RenderCompose returns the compose file that runs one project's sandbox. token is the bearer token the daemon
// requires on every request; it is written into the file, which is created with mode 0600.
func RenderCompose(slug string, s Settings, token string) ([]byte, error) {
	container, err := ContainerName(slug)
	if err != nil {
		return nil, err
	}
	volume, err := VolumeName(slug)
	if err != nil {
		return nil, err
	}
	if s.Image == "" || s.Network == "" {
		return nil, fmt.Errorf("sandbox settings need an image and a network")
	}
	if token == "" {
		return nil, fmt.Errorf("sandbox %s needs a token", slug)
	}
	var buf bytes.Buffer
	data := map[string]string{
		"Slug":      slug,
		"Container": container,
		"Image":     s.Image,
		"Network":   s.Network,
		"Volume":    volume,
		"CapAdd":    strings.Join(capAdd, ", "),
		"Token":     token,
	}
	if err := composeTemplate.Execute(&buf, data); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}
