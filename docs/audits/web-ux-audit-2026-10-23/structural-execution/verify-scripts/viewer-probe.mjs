import { chromium } from 'file:///D:/.VTNet/redteam/raptix/node_modules/playwright/index.mjs';
import { readFileSync } from 'node:fs';
const hold = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const fixtures = JSON.parse(readFileSync(process.argv[3], 'utf8'));
const browser = await chromium.launch({ headless: true });
const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
await page.goto(`${hold.app}/?dataMode=real#/login`, { waitUntil: 'domcontentloaded' });
await page.locator('#login-username').fill(hold.viewer.username);
await page.locator('#login-password').fill(hold.viewer.password);
await page.getByRole('button', { name: 'Sign in' }).click();
await page.getByRole('navigation', { name: 'Main navigation' }).waitFor({ timeout: 30000 });
await page.goto(`${hold.app}/?dataMode=real#/project/${fixtures.project}?tab=team`, { waitUntil: 'domcontentloaded' });
await page.getByText('Waiting for a decision').first().waitFor({ timeout: 30000 });
await page.waitForTimeout(1500);
const found = await page.evaluate(() => [...document.querySelectorAll('button')].filter((b) => /member|invite|add|remove/i.test((b.innerText || b.getAttribute('aria-label') || ''))).map((b) => ({ label: (b.innerText || b.getAttribute('aria-label') || '').trim(), disabled: b.disabled, title: b.title || null })));
console.log(JSON.stringify({ matchingButtons: found }));
const members = await page.evaluate(() => { const card = [...document.querySelectorAll('section, div')].find((el) => el.innerText && el.innerText.startsWith('Members')); return card ? card.innerText.slice(0, 500) : null; });
console.log(JSON.stringify({ membersCard: members }));
await browser.close();
