function node(type, path, name, summary, tags, complexity, lineRange) {
  const n = { id: `${type}:${path}`, type, name, filePath: path, summary, tags, complexity };
  if (lineRange) n.lineRange = lineRange;
  return n;
}
function edge(source, target, type, weight = 0.5) {
  return { source, target, type, direction: 'forward', weight };
}

function buildBatch(idx, nodes, edges) {
  const b = batchesRaw.batches.find((x) => x.batchIndex === idx);
  const batchFiles = b.files.map((f) => ({
    path: f.path,
    language: f.language,
    sizeLines: f.sizeLines,
    fileCategory: f.fileCategory,
  }));
  const ids = new Set(nodes.map((n) => n.id));
  for (const e of edges) {
    if (e.source === e.target) throw new Error(`self-edge in batch ${idx}: ${e.source}`);
    if (!ids.has(e.source)) throw new Error(`edge source not a node in batch ${idx}: ${e.source}`);
  }
  const seen = new Set();
  for (const e of edges) {
    const k = `${e.source}|${e.target}|${e.type}`;
    if (seen.has(k)) throw new Error(`dup edge in batch ${idx}: ${k}`);
    seen.add(k);
  }
  const out = { batchIndex: idx, batchFiles, nodes, edges };
  fs.writeFileSync(`${OUT}/batch-${idx}.json`, JSON.stringify(out, null, 2) + '\n', 'utf8');
  console.log(`batch-${idx}.json: nodes=${nodes.length} edges=${edges.length}`);
}

