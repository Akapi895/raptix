def build_patterns(pairs):
    # loai trung, sap xep dai truoc
    seen = {}
    for a, b in pairs:
        if a not in seen:
            seen[a] = b
    items = sorted(seen.items(), key=lambda kv: len(kv[0]), reverse=True)
    # them bien the gach noi cho tag
    extra = []
    for a, b in items:
        if " " in a and len(a.split()) <= 4:
            extra.append((a.replace(" ", "-"), b.replace(" ", "-")))
    items = sorted(items + extra, key=lambda kv: len(kv[0]), reverse=True)
    pats = []
    for a, b in items:
        pats.append((re.compile(r"(?<![\w])" + re.escape(a) + r"(?![\w])", re.IGNORECASE), a, b))
    return pats

def apply_case(m, acc):
    t = m.group(0)
    if t[:1].isupper():
        return acc[:1].upper() + acc[1:]
    return acc

def main():
    pats = build_patterns(PAIRS)
    text = GEN.read_text(encoding="utf-8")
    # GIU NGUYEN cac khoi code khong phai tieng Viet: chi ap dung trong chuoi summary/tags
    # Don gian: ap dung toan file nhung loai tru cac dong import/def/class/ma ky thuat bang cach
    # chi thay the trong cac chuoi "..." chua tieng Viet (co tu khoa). Kiem tra hau kiem se bat loi.
    orig = text
    total = 0
    for rx, a, b in pats:
        text, n = rx.subn(lambda m: apply_case(m, b), text)
        total += n
    GEN.write_text(text, encoding="utf-8")
    print("replacements=%d" % total)

if __name__ == "__main__":
    main()
